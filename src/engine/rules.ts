// Все числа баланса в одном месте. Движок работает тиками фиксированной длины,
// поэтому скорость игры не зависит от частоты кадров.

export const TICK_HZ = 60;
export const DT = 1 / TICK_HZ;

/** Секунды → целое число тиков. */
export const ticks = (sec: number): number => Math.round(sec * TICK_HZ);

